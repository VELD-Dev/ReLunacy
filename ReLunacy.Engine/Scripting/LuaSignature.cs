namespace ReLunacy.Engine.Scripting;

/// <summary>What a piece of a signature is, so it can be coloured.</summary>
public enum LuaSignaturePart
{
    /// <summary>The <c>(function)</c> prefix.</summary>
    Kind,
    /// <summary>What is being described.</summary>
    Name,
    /// <summary>A parameter's name.</summary>
    Parameter,
    /// <summary>A type, whether a parameter's, a return's or an owner's.</summary>
    Type,
    /// <summary>Punctuation: brackets, commas, colons, <c>?</c>, <c>|</c>.</summary>
    Operator,
    /// <summary>Anything else - a description where a type would go.</summary>
    Text,
}

/// <summary>One coloured piece.</summary>
public readonly record struct LuaSignatureRun(string Text, LuaSignaturePart Part);

/// <summary>
/// Breaks a signature into pieces that can be coloured, and composes the one-line header a hover
/// shows.
///
/// These strings are generated by this codebase - <see cref="LuaApiFunction.Signature"/> and the
/// inferred type names - so the grammar is small and known rather than guessed at. That is what
/// makes taking them apart again reasonable: the probe requires the pieces to join back into the
/// original text exactly, for every signature in a database, so nothing can be dropped or
/// duplicated by a classification mistake.
/// </summary>
public static class LuaSignature
{
    /// <summary>
    /// The header line: <c>(kind) name(parameters): return</c>, or <c>(kind) name: type</c> for
    /// anything that is not called.
    ///
    /// A function with no documented return is shown returning <c>nil</c> rather than with the
    /// return omitted, so the shape of the line does not change depending on how well documented
    /// something is. Note that this does not distinguish a function annotated <c>@return nil</c>
    /// from one with no annotation at all - both say <c>nil</c>.
    /// </summary>
    public static List<LuaSignatureRun> Header(string kind, string name, string? detail)
    {
        var runs = new List<LuaSignatureRun> { new($"({kind})", LuaSignaturePart.Kind),
                                               new(" ", LuaSignaturePart.Text) };

        // A call signature already carries the name - and the owner, for a method - so it replaces
        // the name rather than following it.
        if (detail is { Length: > 0 } text && text.Contains('('))
        {
            runs.AddRange(Parse(text));
            if (!HasReturn(text))
            {
                runs.Add(new(": ", LuaSignaturePart.Operator));
                runs.Add(new("nil", LuaSignaturePart.Type));
            }
            return runs;
        }

        runs.Add(new(name, LuaSignaturePart.Name));
        if (detail is { Length: > 0 } type)
        {
            runs.Add(new(": ", LuaSignaturePart.Operator));
            // A type reads as a type; a sentence where a type would go reads as prose, because
            // some details are descriptions - "undocumented", "a key of M".
            runs.AddRange(LooksLikeType(type) ? Parse(type) : [new(type, LuaSignaturePart.Text)]);
        }
        return runs;
    }

    /// <summary>
    /// Splits a signature or a type into pieces.
    ///
    /// Identifiers are classified by where they sit: before the bracket, the last one is the name
    /// and anything ahead of it is the owner's type; inside, the first of each argument is a
    /// parameter and what follows a colon is its type; after the bracket, everything is a return
    /// type. With no bracket at all it is a type expression, so every identifier is a type.
    /// </summary>
    public static List<LuaSignatureRun> Parse(string text)
    {
        var pieces = Split(text);
        // The bracket is found by CONTAINING '(' rather than by being it: punctuation comes in
        // runs, so a function with no parameters has one piece reading "(): " and looking for a
        // lone "(" finds nothing - which left the name classified as a type.
        int open = pieces.FindIndex(p => p.Text.Contains('('));
        int name = open <= 0 ? -1 : pieces.FindLastIndex(open - 1, p => IsIdentifier(p.Text));

        var runs = new List<LuaSignatureRun>(pieces.Count);
        int depth = 0;
        bool expectingParameter = false;

        for (int i = 0; i < pieces.Count; i++)
        {
            var piece = pieces[i];
            if (!IsIdentifier(piece.Text) && piece.Text != "...")
            {
                foreach (char c in piece.Text)
                {
                    if (c == '(') { depth++; expectingParameter = true; }
                    else if (c == ')') depth--;
                    else if (c == ',' && depth > 0) expectingParameter = true;
                    else if (c == ':') expectingParameter = false;
                }
                runs.Add(new(piece.Text, LuaSignaturePart.Operator));
                continue;
            }

            var part = i == name ? LuaSignaturePart.Name
                     : depth > 0 && expectingParameter ? LuaSignaturePart.Parameter
                     : LuaSignaturePart.Type;
            expectingParameter = false;
            runs.Add(new(piece.Text, part));
        }
        return runs;
    }

    /// <summary>Whether a call signature states what it returns - a colon outside the brackets.</summary>
    private static bool HasReturn(string text)
    {
        int depth = 0;
        foreach (char c in text)
        {
            if (c == '(') depth++;
            else if (c == ')') depth--;
            else if (c == ':' && depth == 0) return true;
        }
        return false;
    }

    /// <summary>
    /// Whether a detail is a type rather than a sentence about one. Types are written without
    /// spaces outside brackets, which separates <c>Moby|nil</c> from "a key of M, declared here".
    /// </summary>
    private static bool LooksLikeType(string text)
    {
        if (text.Length == 0 || text.Contains('\n')) return false;
        int depth = 0;
        foreach (char c in text)
        {
            if (c is '<' or '{' or '(') depth++;
            else if (c is '>' or '}' or ')') depth--;
            else if (char.IsWhiteSpace(c) && depth == 0) return false;
        }
        return true;
    }

    /// <summary>Identifiers and the runs of punctuation between them, in order, losing nothing.</summary>
    private static List<LuaSignatureRun> Split(string text)
    {
        var pieces = new List<LuaSignatureRun>();
        int at = 0;
        while (at < text.Length)
        {
            int start = at;
            if (IsIdentifierChar(text[at]))
            {
                while (at < text.Length && IsIdentifierChar(text[at])) at++;
            }
            else if (text.AsSpan(at).StartsWith("..."))
            {
                at += 3;
                pieces.Add(new("...", LuaSignaturePart.Parameter));
                continue;
            }
            else
            {
                while (at < text.Length && !IsIdentifierChar(text[at])
                       && !text.AsSpan(at).StartsWith("...")) at++;
            }
            pieces.Add(new(text[start..at], LuaSignaturePart.Text));
        }
        return pieces;
    }

    private static bool IsIdentifier(string text) =>
        text.Length > 0 && IsIdentifierChar(text[0]) && !char.IsDigit(text[0]);

    private static bool IsIdentifierChar(char c) => char.IsLetterOrDigit(c) || c == '_';
}
